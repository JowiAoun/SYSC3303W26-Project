/**
 * Component.java
 * 
 * Enumeration representing the three components required to assemble an autonomous drone.
 * Each technician has an infinite supply of one specific component.
 * 
 * @author SYSC 3303 Assignment 1
 * @version 1.0
 */
public enum Component {
    /** The frame component - structural base of the drone */
    FRAME,
    
    /** The propulsion unit - motors and propellers */
    PROPULSION,
    
    /** The control firmware - software/electronics for drone control */
    FIRMWARE
}
